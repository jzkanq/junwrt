HELPER="$TMP_DIR/root/usr/bin/junwrt-adblock"
if [ ! -s "$VIEW" ] || ! grep -q "poll.add(statusPollFn, 10)" "$VIEW" || [ ! -s "$RPC" ] || [ ! -s "$HELPER" ]; then
	echo "The package is incomplete or not the expected Ad Blocker update."
	exit 1
fi

# Preserve the router's existing Ad Blocker settings; seed defaults only if missing.
if [ ! -s /etc/config/junwrt-adblock ]; then
	mkdir -p /etc/config
	cat > /etc/config/junwrt-adblock <<'JUNWRT_ADBLOCK_CONFIG'
config adblock 'main'
	option enabled '0'
	option source 'https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts'
JUNWRT_ADBLOCK_CONFIG
fi

if ! tar -xzf "$TMP_DIR/adblock.tar.gz" -C /; then
	echo "Could not install the Ad Blocker files."
	exit 1
fi

chmod 0755 /usr/bin/junwrt-adblock /etc/init.d/junwrt-adblock
chmod 0644 /usr/share/rpcd/ucode/junwrt-adblock.uc \
	/usr/share/rpcd/acl.d/luci-app-junwrt-adblock.json \
	/usr/share/luci/menu.d/luci-app-junwrt-adblock.json \
	/www/luci-static/resources/view/adblocker.js \
	/www/luci-static/resources/view/adblocker.css

rm -rf /tmp/luci-indexcache /tmp/luci-modulecache
/etc/init.d/rpcd restart

printf '%s\n' "Ad Blocker files installed. Existing configuration preserved."
/usr/bin/junwrt-adblock status
if command -v ubus >/dev/null 2>&1; then
	ubus call junwrt-adblock get_status '{}' || true
fi
printf '%s\n' "Hard-refresh LuCI with Ctrl+Shift+R. This installer did not restart networking or Tailscale."
